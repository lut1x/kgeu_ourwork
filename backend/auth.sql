CREATE TABLE IF NOT EXISTS users (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 email VARCHAR(254) NOT NULL UNIQUE,
 first_name VARCHAR(100) NOT NULL,
 last_name VARCHAR(100) NOT NULL,
 role ENUM('operator','technologist','administrator') NOT NULL DEFAULT 'operator',
 password_hash VARCHAR(200) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS sessions (
 token_hash CHAR(64) PRIMARY KEY,
 user_id INT UNSIGNED NOT NULL,
 expires_at DATETIME NOT NULL,
 FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
 INDEX (expires_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS technical_settings (
 id INT PRIMARY KEY,
 temp_warning DOUBLE NOT NULL DEFAULT 60,
 temp_critical DOUBLE NOT NULL DEFAULT 75
) ENGINE=InnoDB;
INSERT IGNORE INTO technical_settings (id) VALUES (1);
CREATE TABLE IF NOT EXISTS email_challenges (
 id CHAR(64) PRIMARY KEY,
 purpose ENUM('register','reset') NOT NULL,
 email_index CHAR(64) NOT NULL,
 payload TEXT NOT NULL,
 code_hash CHAR(64) NOT NULL,
 user_id INT UNSIGNED NULL,
 actor_id INT UNSIGNED NULL,
 attempts INT NOT NULL DEFAULT 0,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 expires_at DATETIME NOT NULL,
 INDEX (email_index,purpose,created_at),
 INDEX (expires_at),
 FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS account_audit (
 id BIGINT AUTO_INCREMENT PRIMARY KEY,
 actor_id INT UNSIGNED NOT NULL,
 target_id INT UNSIGNED NOT NULL,
 action VARCHAR(40) NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;
